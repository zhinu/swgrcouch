#!/usr/bin/env python3
"""tools/gen-gpdata.py - writes SWGRCouch/Scripts/gpdata.lua (GALACTIC GRAND PRIX track catalogue).

Sources (offline, no game):
  1. the mod's own LIVE track lists (setup.dumpTrackLists, set "arcade", one line per class x planet) grepped from
     UE4SS logs: exactly what RACE SETUP offers and launches -> the speeder pool and the proven pod pool;
  2. the build guide's tracks.json (work/buildguide-scratch) for the Podracing Tour pods on speeder circuits
     (TRAK_MP_*_PLANE etc., pool letter "t": launched through the "game" track set, never raced live yet).
Usage: tools/gen-gpdata.py <lists.txt> <tracks.json> > SWGRCouch/Scripts/gpdata.lua
"""
import json, re, sys

lists_path, tracks_path = sys.argv[1], sys.argv[2]
SPEEDER_PLANETS = ["Mastiff", "Dalmatian", "Husky", "Corgi", "Spaniel", "Whippet"]
POD_PLANETS = ["Beagle", "Dalmatian", "Corgi", "Spaniel", "Mastiff", "Husky"]
# arcade-only pod tracks: 1-2 pod time trials (an 8-pod race on TRAK_WHP_PLANE_FWD crashed, V-TRK-08)
POD_EXCLUDE = {"TRAK_WHP_PLANE_FWD", "TRAK_MAS_PLANE_FWD_Pday", "TRAK_BGL_PLANE_FWD"}
# the online Podracing Tour's pods on speeder circuits (PvpPlaneRunDef, 8-pod races online)
POD_TOUR = ["TRAK_MP_COR_Loop_A_FWD_PLANE", "TRAK_MP_HSK_P2P_FWD_PLANE", "TRAK_MAS_LOOP_B_FWD_MP_PLANE",
            "TRAK_MP_MAS_P2P_FWD_PLANE", "TRAK_MP_DAL_P2P_FWD_PLANE", "TRAK_MP_DAL_LOOP_B_FWD_PLANE",
            "TRAK_HSK_LOOP_A_FWD_MP_PLANE", "TRAK_HSK_LOOP_B_FWD_PDAY_PLANE", "TRAK_MP_COR_Loop_B_FWD_PLANE",
            "TRAK_MP_COR_P2P_FWD_PLANE", "TRAK_MP_COR_P2P_REV_PLANE", "TRAK_MP_SPA_Loop_A_FWD_PLANE"]

lists = {}
for line in open(lists_path, encoding="utf-8"):
    m = re.match(r"track list (\w+) / (\w+) \(set arcade\): \d+: (.*)$", line.strip())
    if not m:
        continue
    cls, planet, body = m.groups()
    out = []
    for ent in body.split(" | "):
        em = re.match(r"(\S+) = (.*?) \[(.*)\]$", ent)
        if not em:
            continue
        key, label, conds = em.groups()
        parts = [p.strip() for p in label.split("  ·  ")]
        name = parts[0]
        flags = [f for p in parts[1:] for f in p.split(" · ")]
        conds = [c.replace("TrackCondition.", "") for c in conds.split(",") if c]
        out.append({"key": key, "name": name, "flags": flags, "conds": conds})
    lists[(cls, planet)] = out

for p in SPEEDER_PLANETS:
    keys = [e["key"] for e in lists[("Car", p)]]
    for c in ("Bike", "Skimmer"):
        assert sorted(e["key"] for e in lists[(c, p)]) == sorted(keys), (c, p)

tj = json.load(open(tracks_path, encoding="utf-8"))
T = {t["id"]: t for t in tj["tracks"]}

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def layout(flags):
    keep = []
    for f in flags:
        f = f.strip()
        if not f or f in keep:
            continue
        keep.append(f)
    return " · ".join(keep)

print("-- gpdata.lua: GALACTIC GRAND PRIX track catalogue (GENERATED by tools/gen-gpdata.py: do not edit by hand).")
print("-- speeders: RACE SETUP's own lists (set \"arcade\", identical for the three speeder classes, live dumps);")
print("-- pods: the 6 Quick Podrace tracks (raced live) + the Podracing Tour pods on speeder circuits (set \"game\",")
print("-- proven = false until a live race confirms them). name = display name, layout = the setup's flags.")
print("local D = {}")
print("D.SPEEDER_PLANETS = { " + ", ".join(lua_str(p) for p in SPEEDER_PLANETS) + " }")
print("D.speeder = {")
for p in SPEEDER_PLANETS:
    print("  %s = {" % p)
    for e in lists[("Car", p)]:
        print("    { key = %s, name = %s, layout = %s, conds = { %s } }," % (
            lua_str(e["key"]), lua_str(e["name"]), lua_str(layout(e["flags"])),
            ", ".join(lua_str(c) for c in e["conds"])))
    print("  },")
print("}")
print("D.pod = {")
for p in POD_PLANETS:
    for e in lists.get(("Plane", p), []):
        if e["key"] in POD_EXCLUDE:
            continue
        print("  { key = %s, planet = %s, name = %s, layout = %s, conds = { %s }, set = \"arcade\", proven = true }," % (
            lua_str(e["key"]), lua_str(p), lua_str(e["name"]), lua_str(layout(e["flags"])),
            ", ".join(lua_str(c) for c in e["conds"])))
for k in POD_TOUR:
    t = T[k]
    lay = t["layout"]
    flags = []
    if lay.get("reverse_flag") or "REV" in k:
        flags.append("REVERSE")
    if lay.get("point_to_point"):
        flags.append("POINT TO POINT")
    conds = [c for c in t.get("conditions") or [] if not c.endswith(".MEM")]
    print("  { key = %s, planet = %s, name = %s, layout = %s, conds = { %s }, set = \"game\", proven = false }," % (
        lua_str(k), lua_str(t["planet"]), lua_str(t["display_name"].upper()), lua_str(" · ".join(flags)),
        ", ".join(lua_str(c) for c in conds)))
print("}")
print("return D")
