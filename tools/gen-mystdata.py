#!/usr/bin/env python3
# gen-mystdata.py - generates SWGRCouch/Scripts/mystdata.lua: the favours of every MysteryInteractionOutcome, keyed
# "<interaction>:<choice>.<outcome>" (the outcome's own object name and its outer chain, e.g.
# "MYST_108_Thrall_SmugglersSpoils:MysteryInteractionChoice_0.MysteryInteractionOutcome_1").
#
# Usage (always python3 -I):
#   python3 -I tools/gen-mystdata.py <out.lua> <cue4cli json dir | json file> [...]
#       e.g. galactic-racer work/decoded-campaign/Griffin/Content/Griffin/Narrative/MysteryInteractions (the 58
#       Mystery-node encounters), work/decoded-mystboss (the field-test / time-trial pre-event interactions) and
#       work/decoded-campaign/Griffin/Content/Griffin/Gameplay/Campaign/DA_CampaignRewardGroups.json (the affix groups)
#
# WHY (FINDING #111 / #67b, crash_2026_10_18_10_24_48 + crash_2026_10_18_03_57_20): ResultFavours is a
# TArray<TSoftObjectPtr<RacerFavour>>. The game (UE 5.7) lays a TSoftObjectPtr out in 0x28 bytes (FWeakObjectPtr 8 +
# FSoftObjectPath 0x20: MysteryInteractionOutcome.ResultBookend +0x100 -> BookendIsConversation +0x128), but UE4SS
# GR Edition's soft-object push (UE4SS.dll+0x2cb760 -> FSoftObjectPath copy +0x4704a0) copies the path from element
# +0x10 (it assumes the UE4 / 5.0 TagAtLastTest int32 after the weak pointer): the path's FString is read 8 bytes too
# far, {Data = the real SubPathString's Num/Max (0), Num = the 4 bytes AFTER the element}. Those bytes are the next
# element's weak pointer or, for the last element, whatever follows the array's heap block: a nonzero value is
# memcpy(dst, NULL, 2*Num) = an access violation pcall cannot catch. So Lua never reads a soft pointer (ARCHITECTURE
# rev 0.5.1, gen-perkdata.py's rule): the favour names come from this static table, the live object only gives the
# outcome's NAME (GetFName) and the list's COUNT (GetArrayNum, header only).
#
# Output: M.OUTCOMES[key] = { favs = { "Favour_MYST_..." | other favour asset name, ... }, bk = true (a ResultBookend),
# pools = { "<RewardPoolDef name>", ... } (ResultAffixRewardPools, in order), run = n (RunUnlock.* ResultUnlockTags: run
# state of P1's run), rm = n (FavoursToRemove) } for every outcome with at least one of them; M.POOLS[name] = the
# RewardPoolDef's groups { {g = "Rare" (AffixGroup.<g>), w = weight, f = FaultyChancePercent, fg = {faulty groups}},
# ..., gen = { {g = primary, s = secondary, w} } (GeneratedAffixGroups) }; M.FOLLOW[interaction] = true for a follow-up
# interaction of an earlier deal (the ResultBookend target of an outcome, or unlocked by a RunUnlock.Mystery.Bookend.*
# tag): it pays / charges the run that made the deal (couch-fix32: never a guest's); M.GROUPS[group] = { affix ids }
# (DA_CampaignRewardGroups, the groups the pools name); M.FAVPATH[favour] = its asset path (couch-fix39: a guest's TEAM
# favour is loaded by this path and added to the shared run, never read from the soft list); M.EVENTS[interaction] = the
# event its outcomes kick off (MysteryInteractionOutcome.ResultEvent, short name: the 94 field-test / time-trial
# pre-event interactions, one event each; couch-fix52). M.DATA_VERSION. Exit 1 on a parse problem (the previous out.lua is
# kept).
#
# couch-fix52 (AUTO-135 / AUTO-137, crash_2026_10_18_16_14_13 / 16_18_16 / 16_22_05 / 17_09_36): ResultEvent is a
# TSoftObjectPtr too (SoftObjectProperty MysteryInteractionOutcome:ResultEvent, +0x180). couch.leavingEvent read it at
# every couch FinishLeaving: UE4SS's member push (+0x2aad40 -> push_softobjectproperty +0x2cb760 -> FSoftObjectPath copy
# +0x4704a0 -> FString copy +0x234545) took Num from the low dword of the NEXT member (DialogueEvent, +0x1a8): a set
# DialogueEvent = memcpy(dst, NULL, 2*Num) (r8 = 0xb3a448 = 2 * 0x59d224). M.EVENTS gives the name without that read.
import glob, json, os, re, sys

DATA_VERSION = "CL381121 decode (work/decoded-campaign + work/decoded-mystboss), generated by tools/gen-mystdata.py"


def short_asset(path):
    # "/Game/.../Passives/Favour_MYST_X.Favour_MYST_X" -> "Favour_MYST_X"
    if not isinstance(path, str) or not path:
        return None
    tail = path.rsplit("/", 1)[-1]
    return tail.split(".", 1)[0] or None


def inner_name(object_name):
    # "MysteryInteractionChoice'MYST_108_X:MysteryInteractionChoice_0'" -> "MYST_108_X:MysteryInteractionChoice_0"
    m = re.match(r"^[^']*'(.*)'$", object_name or "")
    return m.group(1) if m else None


def main():
    if len(sys.argv) < 3:
        sys.stderr.write("usage: python3 -I tools/gen-mystdata.py <out.lua> <json dir> [<json dir> ...]\n")
        return 2
    out, roots = sys.argv[1], sys.argv[2:]
    rows = {}
    favpath = {}
    pools = {}
    follow = set()
    agroups = {}
    events = {}
    nfiles = 0
    for root in roots:
        files = [root] if os.path.isfile(root) else sorted(glob.glob(os.path.join(root, "**", "*.json"), recursive=True))
        for f in files:
            try:
                exports = json.load(open(f, encoding="utf-8"))
            except (OSError, ValueError) as e:
                sys.stderr.write("%s: %s\n" % (f, e))
                return 1
            if not isinstance(exports, list):
                continue
            nfiles += 1
            for e in exports:
                if not isinstance(e, dict):
                    continue
                aff = (e.get("Properties") or {}).get("Affixes")
                if e.get("Name") == "DA_CampaignRewardGroups" and isinstance(aff, list):
                    for g in aff:
                        tag = ((g or {}).get("GroupTag") or {}).get("TagName") or ""
                        ids = [inner_name(x.get("ObjectName")) for x in g.get("Affixes") or [] if isinstance(x, dict)]
                        agroups[tag.replace("AffixGroup.", "")] = [i for i in ids if i]
                    continue
                if e.get("Type") == "RewardPoolDef":
                    pp = e.get("Properties") or {}
                    groups = []
                    for g in pp.get("AffixGroups") or []:
                        tag = ((g or {}).get("RewardGroup") or {}).get("TagName") or ""
                        groups.append({"g": tag.replace("AffixGroup.", ""), "w": float(g.get("Weight", 1.0)),
                                       "f": float(g.get("FaultyChancePercent", 0.0)),
                                       "fg": [x.replace("AffixGroup.", "") for x in g.get("FaultyAffixGroups") or []]})
                    gen = []
                    for g in pp.get("GeneratedAffixGroups") or []:
                        a = ((g or {}).get("PrimaryRewardGroup") or {}).get("TagName") or ""
                        b = ((g or {}).get("SecondaryRewardGroup") or {}).get("TagName") or ""
                        gen.append({"g": a.replace("AffixGroup.", ""), "s": b.replace("AffixGroup.", ""),
                                    "w": float(g.get("Weight", 1.0))})
                    pools[e.get("Name")] = (groups, gen)
                    continue
                if e.get("Type") == "MysteryInteraction":
                    for t in (e.get("Properties") or {}).get("UnlockedByAll") or []:
                        if isinstance(t, str) and t.startswith("RunUnlock.Mystery.Bookend."):
                            follow.add(e.get("Name"))
                    continue
                if e.get("Type") != "MysteryInteractionOutcome":
                    continue
                outer = inner_name((e.get("Outer") or {}).get("ObjectName"))
                if not outer:
                    sys.stderr.write("%s: outcome %s without an outer\n" % (f, e.get("Name")))
                    return 1
                key = "%s.%s" % (outer, e.get("Name"))
                if ":" not in key:          # an outcome directly under the interaction (MandatoryOutcome)
                    key = "%s:%s" % (outer, e.get("Name"))
                p = e.get("Properties") or {}
                evn = short_asset((p.get("ResultEvent") or {}).get("AssetPathName"))
                if evn:
                    inter = key.split(":", 1)[0]
                    if events.get(inter, evn) != evn:
                        sys.stderr.write("%s: interaction %s kicks off two events (%s, %s)\n" % (f, inter, events[inter], evn))
                        return 1
                    events[inter] = evn
                favs = []
                for x in p.get("ResultFavours") or []:
                    n = short_asset((x or {}).get("AssetPathName"))
                    if n:
                        favs.append(n)
                        favpath[n] = (x or {}).get("AssetPathName")
                bkn = short_asset((p.get("ResultBookend") or {}).get("AssetPathName"))
                bk = bkn is not None
                if bk:
                    follow.add(bkn)
                pl = []
                for x in p.get("ResultAffixRewardPools") or []:
                    n = short_asset((x or {}).get("AssetPathName"))
                    if n:
                        pl.append(n)
                run = len([t for t in p.get("ResultUnlockTags") or [] if isinstance(t, str) and t.startswith("RunUnlock.")])
                rm = len(p.get("FavoursToRemove") or [])
                if not favs and not bk and not pl and not run and not rm:
                    continue
                v = (favs, bk, pl, run, rm)
                if key in rows and rows[key] != v:
                    sys.stderr.write("%s: duplicate key %s with other data\n" % (f, key))
                    return 1
                rows[key] = v
    if not rows:
        sys.stderr.write("no outcome with favours found under %s\n" % " ".join(roots))
        return 1
    lines = [
        "-- mystdata.lua - GENERATED by tools/gen-mystdata.py (do not edit): the favours / bookend / reward pools of every",
        "-- mystery outcome, keyed \"<interaction>:<choice>.<outcome>\" (object names), the pools' groups, the follow-up",
        "-- interactions. couchrun.outcomeData reads favours and pools ONLY from here:",
        "-- UE4SS's soft-pointer element read of ResultFavours crashes the game (FINDING #111 / #67b, see the generator).",
        "local M = {}",
        "M.DATA_VERSION = %s" % json.dumps(DATA_VERSION),
        "M.OUTCOMES = {",
    ]
    for key in sorted(rows):
        favs, bk, pl, run, rm = rows[key]
        parts = ["favs = { %s }" % ", ".join(json.dumps(n) for n in favs)]
        if bk:
            parts.append("bk = true")
        if pl:
            parts.append("pools = { %s }" % ", ".join(json.dumps(n) for n in pl))
            for n in pl:
                if n not in pools:
                    sys.stderr.write("outcome %s: reward pool %s not decoded\n" % (key, n))
                    return 1
        if run:
            parts.append("run = %d" % run)
        if rm:
            parts.append("rm = %d" % rm)
        lines.append("  [%s] = { %s }," % (json.dumps(key), ", ".join(parts)))
    lines += ["}", "M.POOLS = {"]

    def num(x):
        return ("%d" % x) if float(x).is_integer() else ("%g" % x)
    for n in sorted(pools):
        groups, gen = pools[n]
        gs = ["{ g = %s, w = %s, f = %s, fg = { %s } }" % (json.dumps(g["g"]), num(g["w"]), num(g["f"]),
              ", ".join(json.dumps(x) for x in g["fg"])) for g in groups]
        ge = ["{ g = %s, s = %s, w = %s }" % (json.dumps(g["g"]), json.dumps(g["s"]), num(g["w"])) for g in gen]
        lines.append("  [%s] = { %s }," % (json.dumps(n), ", ".join(gs + (["gen = { %s }" % ", ".join(ge)] if ge else []))))
    used = set()
    for groups, gen in pools.values():
        for g in groups:
            if g["w"] > 0:
                used.add(g["g"])
                used.update(g["fg"])
        for g in gen:
            used.add(g["g"])
            used.add(g["s"])
    missing = sorted(u for u in used if u not in agroups)
    if missing:
        sys.stderr.write("affix group(s) %s not decoded (pass DA_CampaignRewardGroups.json)\n" % ", ".join(missing))
        return 1
    lines += ["}", "M.GROUPS = {"]
    for g in sorted(used):
        lines.append("  [%s] = { %s }," % (json.dumps(g), ", ".join(json.dumps(i) for i in agroups[g])))
    lines += ["}", "M.FAVPATH = {"]
    for n in sorted(favpath):
        lines.append("  [%s] = %s," % (json.dumps(n), json.dumps(favpath[n])))
    lines += ["}", "M.EVENTS = {"]
    for n in sorted(events):
        lines.append("  [%s] = %s," % (json.dumps(n), json.dumps(events[n])))
    lines += ["}", "M.FOLLOW = {"]
    for n in sorted(follow):
        lines.append("  [%s] = true," % json.dumps(n))
    lines += ["}", "return M", ""]
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    os.replace(tmp, out)
    print("mystdata: %d file(s), %d outcome(s) with favours / bookends / pools, %d pool(s), %d follow-up(s), %d event "
          "interaction(s) -> %s" % (nfiles, len(rows), len(pools), len(follow), len(events), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
